"""Write CREDITS.md from every data/<slug>/photos.json: one row per photo with author, licence and source page.
usage: make_credits.py"""
import json,glob,os,re
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows=[]
for f in sorted(glob.glob(os.path.join(ROOT,'data','*','photos.json'))):
    slug=f.split(os.sep)[-2]
    for key,m in json.load(open(f)).items():
        artist=re.sub(r'\s+',' ',re.sub('<[^>]+>','',m.get('artist','')).split(' from ')[0]).strip() or 'unknown'
        rows.append((slug,key,artist,m.get('license','?'),m.get('page','')))
out=['# Photo credits','',
 'Every photograph in `data/<guide>/photos/` is the work of the person named here and is used under the licence shown.',
 'They are not covered by any licence that applies to the rest of this repository. Photos are resized for print and some',
 'are cropped; those marked ND are used uncropped. Generated by `scripts/make_credits.py`.','',
 '| Guide | Photo | Author | Licence | Source |','|---|---|---|---|---|']
out+=['| %s | `%s.jpg` | %s | %s | %s |'%(s,k,a.replace('|','/'),l,('[page](%s)'%p) if p else '') for s,k,a,l,p in rows]
open(os.path.join(ROOT,'CREDITS.md'),'w').write('\n'.join(out)+'\n');print(len(rows),'photos')
