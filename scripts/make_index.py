"""Write the hike lists (BAY-AREA-HIKES.md, FURTHER-AFIELD.md) from every built guide: for each hike its cover
photo, its blurb (the guide's subtitle), the headline figures and links to the PDFs and GPX tracks, then a table.
Each guide's config may set REGION='bay-area' (default: further afield). Text and figures are read from the built
feet-and-miles guide (out/<slug>/guide.html), so run `make` first.
usage: make_index.py"""
import re,glob,os,html,json
from hikelib import load_config,ROOT
clean=lambda x:html.unescape(re.sub(r'\s+',' ',re.sub('<[^>]+>',' ',x))).strip()
hikes={'bay-area':[],'further':[]}
for cfg in sorted(glob.glob(os.path.join(ROOT,'guides','*','config.py'))):
    slug=cfg.split(os.sep)[-2];C=load_config(slug);f=os.path.join(C.OUT,'guide.html')
    if not os.path.exists(f):continue
    h=re.sub(r'<svg.*?</svg>|base64,[^"]+','',open(f).read(),flags=re.S)
    title=clean(re.search(r'<h1>(.*?)</h1>',h,re.S).group(1));kick=clean(re.search(r'class="kicker">(.*?)</div>',h,re.S).group(1))
    sub=re.search(r'<p class="sub">(.*?)</p>',h,re.S);blurb=clean(sub.group(1)) if sub else ''
    kind,_,where=kick.partition(' · ')
    cells=[clean(a) for a,b in re.findall(r'<div><b>(.*?)</b><span>(.*?)</span></div>',h,re.S)[:5]]
    notes=[clean(b) for a,b in re.findall(r'<div><b>(.*?)</b><span>(.*?)</span></div>',h,re.S)[:5]]
    base='out/%s/'%slug;pdf=C.PDF.replace('-metric','').replace('-a4','');a4=pdf.replace('.pdf','-metric-a4.pdf')
    links=['[Print it: Letter, feet and miles](%s%s)'%(base,pdf)]
    if os.path.exists(os.path.join(C.OUT,a4)):links.append('[A4, metric](%s%s)'%(base,a4))
    links+=['[GPX%s](%s%s-%s.gpx)'%('' if len(C.GPX)==1 else ': '+k,base,slug,k) for k in C.GPX if os.path.exists(os.path.join(C.OUT,'%s-%s.gpx'%(slug,k)))]
    # cover photo = the first photo the template uses, credited from photos.json
    key=re.search(r'\{\{PHOTO:(\w+)\}\}',open(os.path.join(C.DIR,'template.html')).read());photo=''
    meta=os.path.join(C.DATA,'photos.json')
    if key and os.path.exists(os.path.join(C.DATA,'photos',key.group(1)+'.jpg')) and os.path.exists(meta):
        m=json.load(open(meta)).get(key.group(1),{});artist=clean(m.get('artist','')).split(' from ')[0]
        photo='![%s](data/%s/photos/%s.jpg)\n\n<sub>Photo: %s, %s%s</sub>\n\n'%(title,slug,key.group(1),artist or 'unknown',m.get('license','?'),(' ([source](%s))'%m['page']) if m.get('page') else '')
    miles=float(re.sub(r'[^0-9.]','',cells[0]) or 0)
    section='## %s\n\n*%s · %s*\n\n%s%s\n\n**%s** %s · **%s** %s · **%s** · **%s**: %s\n\n%s\n'%(title,where or kind,kind.lower() if where else '',photo,blurb,cells[0],notes[0],cells[1],notes[1],cells[2],cells[4],notes[4],' · '.join(links))
    row='| [%s](#%s) | %s | %s | %s | %s |'%(title,re.sub(r'[^a-z0-9 -]','',title.lower()).replace(' ','-'),cells[0],cells[1],cells[2],cells[4])
    hikes['bay-area' if getattr(C,'REGION','')=='bay-area' else 'further'].append((miles,section,row))
def write(name,title,intro,key):
    hs=sorted(hikes[key])
    body='# %s\n\n%s\n\n'%(title,intro)+'\n'.join(s for _,s,_ in hs)
    body+='\n## At a glance\n\n| Hike | Distance | Climb | Time | Grade |\n|---|---|---|---|---|\n'+'\n'.join(r for _,_,r in hs)
    body+='\n\nFigures are for the feet-and-miles edition. Each guide is 5 or 6 pages. Photos belong to their authors: see [CREDITS.md](CREDITS.md). Generated by `scripts/make_index.py`.\n'
    open(os.path.join(ROOT,name),'w').write(body);print(name,len(hs))
write('BAY-AREA-HIKES.md','Bay Area hikes','Printable guides to hikes within about an hour and a half of San Francisco, shortest first. Each is a PDF to print and carry; the [README](README.md) explains what goes into one and how to print it so it survives rain.','bay-area')
write('FURTHER-AFIELD.md','Further afield','Printable guides to hikes and backpacking trips elsewhere in California and in the Rockies, shortest first. Each is a PDF to print and carry; the [README](README.md) explains what goes into one and how to print it so it survives rain.','further')
