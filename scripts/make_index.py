"""Write the hike lists (BAY-AREA-HIKES.md, FURTHER-AFIELD.md) from every built guide.
Each guide's config may set REGION='bay-area' (default: further afield). Figures are read from the built
feet-and-miles guide (out/<slug>/guide.html), so run `make` first.
usage: make_index.py"""
import re,glob,os,html
from hikelib import load_config,ROOT
clean=lambda x:html.unescape(re.sub(r'\s+',' ',re.sub('<[^>]+>',' ',x))).strip()
rows={'bay-area':[],'further':[]}
for cfg in sorted(glob.glob(os.path.join(ROOT,'guides','*','config.py'))):
    slug=cfg.split(os.sep)[-2];C=load_config(slug);f=os.path.join(C.OUT,'guide.html')
    if not os.path.exists(f):continue
    h=re.sub(r'<svg.*?</svg>|base64,[^"]+','',open(f).read(),flags=re.S)
    title=clean(re.search(r'<h1>(.*?)</h1>',h,re.S).group(1));kick=clean(re.search(r'class="kicker">(.*?)</div>',h,re.S).group(1))
    kind,_,where=kick.partition(' · ')
    cells=[clean(a) for a,b in re.findall(r'<div><b>(.*?)</b><span>(.*?)</span></div>',h,re.S)[:5]]
    pdf=C.PDF.replace('-metric','').replace('-a4','');base='out/%s/'%slug
    miles=float(re.sub(r'[^0-9.]','',cells[0]) or 0)
    links='[PDF](%s%s)'%(base,pdf)+(' · [metric A4](%s%s)'%(base,pdf.replace('.pdf','-metric-a4.pdf')) if os.path.exists(os.path.join(C.OUT,pdf.replace('.pdf','-metric-a4.pdf'))) else '')
    rows['bay-area' if getattr(C,'REGION','')=='bay-area' else 'further'].append((miles,'| **%s** | %s | %s | %s | %s | %s | %s |'%(title,where or kind,cells[0],cells[1],cells[2],cells[4],links)))
HEAD='| Hike | Where | Distance | Climb | Time | Grade | Print |\n|---|---|---|---|---|---|---|\n'
def write(name,title,intro,key):
    body='# %s\n\n%s\n\n'%(title,intro)+HEAD+'\n'.join(r for _,r in sorted(rows[key]))+'\n\nFigures are for the feet-and-miles edition. Each guide is 5 or 6 pages, US Letter; the metric edition is A4. GPX tracks are in each guide\'s `out/` folder. Generated by `scripts/make_index.py`.\n'
    open(os.path.join(ROOT,name),'w').write(body);print(name,len(rows[key]))
write('BAY-AREA-HIKES.md','Bay Area hikes','Printable guides to hikes within about an hour and a half of San Francisco, shortest first. See the [README](README.md) for what these are.','bay-area')
write('FURTHER-AFIELD.md','Further afield','Printable guides to hikes and backpacking trips elsewhere in California and the Rockies, shortest first. See the [README](README.md) for what these are.','further')
